import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { existsSync, readdirSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const scriptDir = path.dirname(fileURLToPath(import.meta.url));
const packageDir = path.resolve(scriptDir, '..');
const sourcePath = path.resolve(packageDir, 'src/styles/themes/bikeshed.css');
const generatedTsPath = path.resolve(packageDir, 'src/styles/generated/bikeshed.css.ts');

async function loadTailwindNodeApi() {
  const pnpmRoot = path.resolve(packageDir, '..', '..', 'node_modules', '.pnpm');
  if (!existsSync(pnpmRoot)) {
    return null;
  }

  const tailwindEntry = readdirSync(pnpmRoot).find((entry) =>
    entry.startsWith('@tailwindcss+node@')
  );
  const candidate = tailwindEntry
    ? path.join(
        pnpmRoot,
        tailwindEntry,
        'node_modules',
        '@tailwindcss',
        'node',
        'dist',
        'index.mjs'
      )
    : '';

  if (!existsSync(candidate)) {
    return null;
  }

  return import(pathToFileURL(candidate).href);
}

async function build() {
  const source = await readFile(sourcePath, 'utf8');
  const tailwindNode = await loadTailwindNodeApi();

  let optimizedCss = '';
  const canCompile = tailwindNode?.compile && tailwindNode?.optimize;

  if (canCompile) {
    try {
      // Find all tsx files to scan and extract potential tailwind classes
      const getAllFiles = (dir, fileList = []) => {
        const files = readdirSync(dir, { withFileTypes: true });
        for (const file of files) {
          if (file.isDirectory()) {
            getAllFiles(path.join(dir, file.name), fileList);
          } else if (file.name.endsWith('.tsx') || file.name.endsWith('.ts')) {
            fileList.push(path.join(dir, file.name));
          }
        }
        return fileList;
      };
      
      const componentFiles = getAllFiles(path.resolve(packageDir, 'src'));
      const candidates = new Set();
      for (const file of componentFiles) {
        const content = await readFile(file, 'utf8');
        const words = content.match(/[\w\-:./]+/g) || [];
        for (const word of words) {
          candidates.add(word);
        }
      }
      
      const compiler = await tailwindNode.compile(source, {
        base: path.dirname(sourcePath),
        from: sourcePath,
        onDependency: () => {},
      });
      const compiledCss = compiler.build(Array.from(candidates));
      optimizedCss = tailwindNode.optimize(compiledCss, { minify: true }).code;
    } catch {
      optimizedCss = source
        .replace(/@import\s+"tailwindcss";\s*/g, '')
        .replace(/@custom-variant[^\n]*\n/g, '')
        .replace(/@theme\s*\{[\s\S]*?\}\s*/g, '')
        .trim();
    }
  } else {
    optimizedCss = source
      .replace(/@import\s+"tailwindcss";\s*/g, '')
      .replace(/@custom-variant[^\n]*\n/g, '')
      .replace(/@theme\s*\{[\s\S]*?\}\s*/g, '')
      .trim();
  }

  const fileContents = `/* This file is generated by scripts/build-theme-css.mjs. */\nexport const BIKESHED_THEME_CSS = ${JSON.stringify(optimizedCss)};\n`;

  await mkdir(path.dirname(generatedTsPath), { recursive: true });
  await writeFile(generatedTsPath, fileContents, 'utf8');
  process.stdout.write(
    `[solospec] generated ${path.relative(packageDir, generatedTsPath)} (${optimizedCss.length} bytes)\n`
  );
}

build().catch((error) => {
  process.stderr.write(`[solospec] theme css build failed: ${String(error)}\n`);
  process.exitCode = 1;
});

import { readdir, readFile, writeFile, mkdir } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const scriptDir = path.dirname(fileURLToPath(import.meta.url));
const packageDir = path.resolve(scriptDir, '..');
const themesTokensDir = path.resolve(packageDir, 'tokens', 'themes');
const generatedTokensDir = path.resolve(packageDir, 'src', 'styles', 'generated', 'themes');

function isObject(value) {
  return typeof value === 'object' && value !== null && !Array.isArray(value);
}

function isTokenLeaf(value) {
  return isObject(value) && Object.prototype.hasOwnProperty.call(value, '$value');
}

function collectTokens(node, pathParts = [], inheritedType, out = new Map()) {
  if (!isObject(node)) {
    return out;
  }

  if (isTokenLeaf(node)) {
    const tokenPath = pathParts.join('.');
    out.set(tokenPath, {
      type: typeof node.$type === 'string' ? node.$type : inheritedType,
      value: node.$value,
    });
    return out;
  }

  const nextInheritedType = typeof node.$type === 'string' ? node.$type : inheritedType;
  for (const [key, value] of Object.entries(node)) {
    if (key.startsWith('$')) {
      continue;
    }
    collectTokens(value, [...pathParts, key], nextInheritedType, out);
  }

  return out;
}

function mergeJsonObjects(target, source) {
  for (const [key, sourceValue] of Object.entries(source)) {
    const targetValue = target[key];
    if (isObject(targetValue) && isObject(sourceValue) && !isTokenLeaf(sourceValue)) {
      mergeJsonObjects(targetValue, sourceValue);
      continue;
    }
    target[key] = sourceValue;
  }
}

function toCssVarName(tokenPath) {
  const normalized = tokenPath
    .split('.')
    .map((part) => part.replace(/([a-z0-9])([A-Z])/g, '$1-$2').toLowerCase())
    .join('-');
  return `--dt-${normalized}`;
}

function toCssValue(value) {
  if (typeof value === 'string') {
    return value;
  }
  if (typeof value === 'number') {
    return String(value);
  }
  if (Array.isArray(value)) {
    return value.join(', ');
  }
  if (isObject(value)) {
    const keys = ['x', 'y', 'blur', 'spread', 'color'];
    if (keys.every((key) => key in value)) {
      return `${value.x} ${value.y} ${value.blur} ${value.spread} ${value.color}`;
    }
  }
  return String(value);
}

function createAliasResolver(tokens) {
  const resolving = new Set();
  const cache = new Map();

  function resolveTokenValue(tokenPath) {
    if (cache.has(tokenPath)) {
      return cache.get(tokenPath);
    }

    if (resolving.has(tokenPath)) {
      throw new Error(`Token alias cycle detected at "${tokenPath}"`);
    }

    const token = tokens.get(tokenPath);
    if (!token) {
      throw new Error(`Token alias target "${tokenPath}" not found`);
    }

    resolving.add(tokenPath);
    let resolvedValue = token.value;

    if (typeof resolvedValue === 'string') {
      const match = resolvedValue.match(/^\{([A-Za-z0-9_.-]+)\}$/);
      if (match) {
        resolvedValue = resolveTokenValue(match[1]);
      }
    }

    resolving.delete(tokenPath);
    cache.set(tokenPath, resolvedValue);
    return resolvedValue;
  }

  return resolveTokenValue;
}

async function readThemeTokenTree(themePath) {
  const entries = await readdir(themePath, { withFileTypes: true });
  const jsonFiles = entries
    .filter((entry) => entry.isFile() && entry.name.endsWith('.json'))
    .map((entry) => entry.name)
    .sort((a, b) => a.localeCompare(b));

  const mergedTree = {};
  for (const fileName of jsonFiles) {
    const filePath = path.join(themePath, fileName);
    const raw = await readFile(filePath, 'utf8');
    const parsed = JSON.parse(raw);
    mergeJsonObjects(mergedTree, parsed);
  }

  return mergedTree;
}

async function buildThemeTokens() {
  const themeEntries = await readdir(themesTokensDir, { withFileTypes: true });
  const themeNames = themeEntries
    .filter((entry) => entry.isDirectory())
    .map((entry) => entry.name)
    .sort((a, b) => a.localeCompare(b));

  if (themeNames.length === 0) {
    process.stdout.write('[solospec] no token themes found, skipping token generation.\n');
    return;
  }

  await mkdir(generatedTokensDir, { recursive: true });

  for (const themeName of themeNames) {
    const themePath = path.join(themesTokensDir, themeName);
    const tokenTree = await readThemeTokenTree(themePath);
    const tokenMap = collectTokens(tokenTree);
    const resolveAlias = createAliasResolver(tokenMap);

    const cssLines = [];
    for (const tokenPath of Array.from(tokenMap.keys()).sort((a, b) => a.localeCompare(b))) {
      const resolvedValue = resolveAlias(tokenPath);
      cssLines.push(`  ${toCssVarName(tokenPath)}: ${toCssValue(resolvedValue)};`);
    }

    const css = [
      '/* This file is generated by scripts/build-theme-tokens.mjs. */',
      `:where(.solospec-root[data-solospec-theme="${themeName}"]) {`,
      ...cssLines,
      '}',
      '',
    ].join('\n');

    const outputPath = path.join(generatedTokensDir, `${themeName}.tokens.css`);
    await writeFile(outputPath, css, 'utf8');
    process.stdout.write(
      `[solospec] generated ${path.relative(packageDir, outputPath)} (${css.length} bytes)\n`
    );
  }
}

export { buildThemeTokens };

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  buildThemeTokens().catch((error) => {
    process.stderr.write(`[solospec] token build failed: ${String(error)}\n`);
    process.exitCode = 1;
  });
}
